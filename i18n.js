let currentLang = localStorage.getItem('lang') || 'zh';
const langOrder = ['zh', 'zhTW', 'en', 'ja'];

function t(key, params = {}) {
    let text = i18n[currentLang][key] || i18n['zh'][key] || key;
    Object.keys(params).forEach(k => {
        text = text.replace('{' + k + '}', params[k]);
    });
    return text;
}

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('lang', lang);
    document.getElementById('langToggle').textContent = i18n[lang].langToggle;
    applyTranslations();
    if (typeof updatePagination === 'function') updatePagination();
}

function applyTranslations() {
    // standard text nodes
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key);
    });

    // placeholders for inputs/textareas
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (el) el.setAttribute('placeholder', t(key));
    });

    // innerHTML for elements that need HTML content (use carefully)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (el) el.innerHTML = t(key);
    });

    // value for inputs/buttons
    document.querySelectorAll('[data-i18n-value]').forEach(el => {
        const key = el.getAttribute('data-i18n-value');
        if (el && typeof el.value !== 'undefined') el.value = t(key);
    });

    // arbitrary attributes: data-i18n-attr="attr:key,attr2:key2"
    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
        const spec = el.getAttribute('data-i18n-attr');
        if (!spec) return;
        spec.split(/[;,]+/).forEach(pair => {
            const parts = pair.split(':');
            if (parts.length < 2) return;
            const attr = parts[0].trim();
            const key = parts.slice(1).join(':').trim();
            if (attr && key) el.setAttribute(attr, t(key));
        });
    });

    // backward-compatible specific selectors
    updateElementText('.section-title', 'sectionTitle');
    updateElementText('.divider-content', 'dividerContent');
    updateElementPlaceholder('#num1', 'num1');
    updateElementPlaceholder('#num2', 'num2');
}

function updateElementText(selector, key) {
    const el = document.querySelector(selector);
    if (el) el.textContent = t(key);
}

function updateElementPlaceholder(selector, key) {
    const el = document.querySelector(selector);
    if (el && typeof el.setAttribute === 'function') el.setAttribute('placeholder', t(key));
}

const langToggle = document.getElementById('langToggle');
const langMenu = document.getElementById('langMenu');
let menuOpen = false;

langToggle.addEventListener('click', (e) => {
    e.stopPropagation();
    menuOpen = !menuOpen;
    langMenu.classList.toggle('show', menuOpen);
    updateLangMenuActive();
});

document.addEventListener('click', (e) => {
    if (menuOpen && !e.target.closest('.lang-dropdown')) {
        menuOpen = false;
        langMenu.classList.remove('show');
    }
});

document.querySelectorAll('.lang-option').forEach(option => {
    option.addEventListener('click', () => {
        const lang = option.getAttribute('data-lang');
        setLanguage(lang);
        menuOpen = false;
        langMenu.classList.remove('show');
    });
});

function updateLangMenuActive() {
    document.querySelectorAll('.lang-option').forEach(option => {
        const lang = option.getAttribute('data-lang');
        option.classList.toggle('active', lang === currentLang);
    });
}

